<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class Enquiry extends Model
{
    /**
     * Database table.
     */
    protected $table = 'enquiries';

    /**
     * Primary key.
     */
    protected $primaryKey = 'id';

    /**
     * Fields that can be mass assigned.
     */
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | Enquiry
        |--------------------------------------------------------------------------
        */

        'enquiry_number',

        /*
        |--------------------------------------------------------------------------
        | Student Details
        |--------------------------------------------------------------------------
        */

        'first_name',
        'last_name',
        'dob',
        'gender',

        /*
        |--------------------------------------------------------------------------
        | Admission Details
        |--------------------------------------------------------------------------
        */

        'class',

        /*
        |--------------------------------------------------------------------------
        | Parent Details
        |--------------------------------------------------------------------------
        */

        'father_name',
        'mother_name',

        /*
        |--------------------------------------------------------------------------
        | Contact Details
        |--------------------------------------------------------------------------
        */

        'contact_no',
        'email',

        /*
        |--------------------------------------------------------------------------
        | School Details
        |--------------------------------------------------------------------------
        */

        'current_school',

        /*
        |--------------------------------------------------------------------------
        | Documents
        |--------------------------------------------------------------------------
        */

        'all_documents_available',

        /*
        |--------------------------------------------------------------------------
        | Enquiry Question
        |--------------------------------------------------------------------------
        */

        'question',
    ];

    /**
     * Cast database fields to appropriate types.
     */
    protected $casts = [

        'dob' => 'date',

    ];
}